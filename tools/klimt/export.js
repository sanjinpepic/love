// Paints the Klimt walk's assets once, at high resolution with the full brush,
// and saves them for the site: the trees (trunk + crown), the deep wood, and the valley.
//   ADMIN_PASSWORD=x PORT=8077 python3 server/server.py &   (any static server works)
//   node tools/klimt/export.js http://localhost:8077
"use strict";
const fs = require("fs");
const path = require("path");
const { chromium } = require("playwright");

const base = process.argv[2] || "http://localhost:8000";
const out = path.join(__dirname, "..", "..", "assets", "klimt");

(async () => {
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
  page.on("pageerror", (e) => console.error("pageerror", e.message));
  await page.goto(base + "/?export=1", { waitUntil: "load" });
  await page.waitForFunction(() => window.__klimtExport, null, { timeout: 600000, polling: 1000 });
  const data = await page.evaluate(() => window.__klimtExport);
  const save = (name, url) => {
    const buf = Buffer.from(url.split(",")[1], "base64");
    fs.writeFileSync(path.join(out, name), buf);
    return name;
  };
  const manifest = { v: new Date().toISOString().replace(/\D/g, "").slice(0, 12), trees: [], glints: data.glints.map((g) => g.map((v) => Math.round(v * 10000) / 10000)) };
  data.trees.forEach((t, i) => {
    const { trunk, crown, ...meta } = t;
    manifest.trees.push({ ...meta, trunk: save(`tree-${i}-trunk.webp`, trunk), crown: crown ? save(`tree-${i}-crown.webp`, crown) : null });
  });
  manifest.ground = save("ground.webp", data.ground);
  manifest.path = save("path.webp", data.path);
  manifest.valley = save("valley.webp", data.valley);
  save("glade.webp", data.glade);
  [["cut-birch", "cutBirch"], ["cut-spruce", "cutSpruce"], ["cut-fern", "cutFern"], ["day-ribbon", "dayH"], ["day-ribbon-v", "dayV"], ["river-ribbon", "river"], ["wood-band", "wood"]].forEach(([f, k]) => save(f + ".webp", data[k]));
  fs.writeFileSync(path.join(out, "assets.js"), "/* generated by tools/klimt/export.js */\nwindow.KLIMT_ASSETS = " + JSON.stringify(manifest) + ";\n");
  const total = fs.readdirSync(out).reduce((n, f) => n + fs.statSync(path.join(out, f)).size, 0);
  console.log(`${fs.readdirSync(out).length} files, ${(total / 1024).toFixed(0)} KB`);
  await browser.close();
})();

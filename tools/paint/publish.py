# Convert rendered PNG layers to WebP for the site and write the scene manifest.
#   python3 tools/paint/publish.py
import json
from pathlib import Path
from PIL import Image
here = Path(__file__).parent
out, dest = here / "out", here.parent.parent / "assets" / "paint"
dest.mkdir(parents=True, exist_ok=True)
m = json.load(open(out / "manifest.json"))
def conv(name, q=72):
    im = Image.open(out / name)
    target = dest / (Path(name).stem + ".webp")
    im.save(target, "WEBP", quality=q, method=4, alpha_quality=70)
    return target.name
for k, L in m.items():
    if k == "vignettes":
        for v in L.values(): v["file"] = conv(v["file"])
        continue
    for layer in L["layers"]: layer["file"] = conv(layer["file"], 80 if layer["id"] == "sky" else 70)
    for s in L["sprites"]: s["file"] = conv(s["file"])
    L["sun"]["file"] = conv(L["sun"]["file"], 90)
# a flattened poster per layout: shown at once while the layers load
for k, L in m.items():
    if k == "vignettes": continue
    base = None
    for layer in L["layers"]:
        im = Image.open(out / layer["file"].replace(".webp", ".png")).convert("RGBA")
        base = im if base is None else Image.alpha_composite(base, im)
    base.convert("RGB").resize((L["W"] // 2, L["H"] // 2), Image.LANCZOS).save(dest / f"{k}-poster.webp", "WEBP", quality=55, method=4)
    L["poster"] = f"{k}-poster.webp"
(dest / "manifest.json").write_text(json.dumps(m, indent=1))
# the same data for the pages, without a fetch
(dest.parent / "js" / "scene-data.js").write_text("/* generated by tools/paint/publish.py */\nwindow.SCENE = " + json.dumps(m) + ";\n")
total = sum(p.stat().st_size for p in dest.glob("*.webp"))
print(f"{len(list(dest.glob('*.webp')))} files, {total/1024:.0f} KB")
